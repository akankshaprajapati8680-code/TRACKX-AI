"""
simulate.py - SIMULATED ultrasonic waveform generator for TrackX AI.

!!! IMPORTANT !!!
Everything produced here is SYNTHETIC. It is a toy model used only to develop
and test the software pipeline (features -> classifier -> dashboard) before
real labelled rail data from an NDT lab is available. Results obtained on this
data say NOTHING about real-world detection performance.

Model (pulse-echo, Node A):
  * transmit pulse "bang" at t = 0
  * end-of-rail echo (back wall) at a known delay
  * defect: extra, earlier echo + weaker end echo (shadowing)
  * nuisance variation: coupling gain, temperature (velocity drift), noise,
    weld/joint-like benign reflections
  * "bad_coupling": very weak / noisy capture (should become Inconclusive)

Usage:
    python -m src.simulate --n 300 --out data/simulated
"""
from __future__ import annotations

import argparse
import json
from pathlib import Path

import numpy as np
import pandas as pd

FS = 10e6            # sampling rate [Hz] (placeholder; fixed during prototyping)
N_SAMPLES = 2000     # 200 microseconds per capture
F0 = 2.25e6          # probe centre frequency [Hz] (placeholder)
RAIL_VELOCITY = 5900.0  # approx. longitudinal velocity in steel [m/s]
END_DISTANCE_M = 0.35   # probe -> back wall (toy value)

LABELS = {0: "normal", 1: "potentially_defective"}


def _pulse(t, t0, amp, f0=F0, bw=0.45e-6):
    """Gaussian-windowed sine burst centred at t0."""
    tau = t - t0
    return amp * np.exp(-(tau / bw) ** 2) * np.sin(2 * np.pi * f0 * tau)


def make_waveform(kind, rng):
    """Create one synthetic waveform. kind in {normal, defect, bad_coupling}."""
    t = np.arange(N_SAMPLES) / FS
    coupling = rng.uniform(0.7, 1.3)
    temp_drift = rng.normal(0.0, 0.004)
    velocity = RAIL_VELOCITY * (1 + temp_drift)
    t_end = 2 * END_DISTANCE_M / velocity
    noise_sigma = rng.uniform(0.015, 0.04)

    sig = _pulse(t, 5e-6, 1.0 * coupling)
    meta = {"kind": kind, "coupling": coupling, "temp_drift": temp_drift,
            "noise_sigma": noise_sigma, "has_defect": 0}

    end_amp = rng.uniform(0.45, 0.6) * coupling
    if kind == "normal":
        if rng.random() < 0.3:  # benign weld/joint reflection (nuisance, NOT a defect)
            sig += _pulse(t, 5e-6 + rng.uniform(0.3, 0.8) * t_end, rng.uniform(0.04, 0.1) * coupling)
        sig += _pulse(t, 5e-6 + t_end, end_amp)
    elif kind == "defect":
        meta["has_defect"] = 1
        frac = rng.uniform(0.25, 0.8)
        d_amp = rng.uniform(0.15, 0.4) * coupling
        sig += _pulse(t, 5e-6 + frac * t_end, d_amp)
        sig += _pulse(t, 5e-6 + t_end, end_amp * rng.uniform(0.35, 0.7))
    elif kind == "bad_coupling":
        sig = _pulse(t, 5e-6, 0.25 * coupling)
        sig += _pulse(t, 5e-6 + t_end, end_amp * 0.08)
        noise_sigma *= rng.uniform(2.5, 4.0)
        meta["noise_sigma"] = noise_sigma
    else:
        raise ValueError(kind)

    sig = sig + rng.normal(0, noise_sigma, size=t.shape)
    return sig.astype(np.float32), meta


def generate_dataset(n_per_class=300, n_bad=60, seed=42):
    rng = np.random.default_rng(seed)
    waves, rows = [], []
    for kind, n in (("normal", n_per_class), ("defect", n_per_class), ("bad_coupling", n_bad)):
        for _ in range(n):
            w, m = make_waveform(kind, rng)
            m["id"] = len(waves)
            m["session"] = int(rng.integers(0, 6))   # fake "session" id for group splits
            m["SIMULATED"] = True
            waves.append(w)
            rows.append(m)
    return np.vstack(waves), pd.DataFrame(rows)


def main():
    ap = argparse.ArgumentParser(description="Generate SIMULATED rail waveforms")
    ap.add_argument("--n", type=int, default=300, help="waveforms per class")
    ap.add_argument("--bad", type=int, default=60, help="bad-coupling waveforms")
    ap.add_argument("--seed", type=int, default=42)
    ap.add_argument("--out", default="data/simulated")
    a = ap.parse_args()

    out = Path(a.out)
    out.mkdir(parents=True, exist_ok=True)
    X, meta = generate_dataset(a.n, a.bad, a.seed)
    np.savez_compressed(out / "waveforms_SIMULATED.npz", waveforms=X, fs=FS)
    meta.to_csv(out / "metadata_SIMULATED.csv", index=False)
    (out / "README.txt").write_text(
        "SIMULATED DATA - NOT MEASURED.\n"
        "Generated by src/simulate.py with a toy pulse-echo model.\n"
        f"fs={FS} Hz, samples={N_SAMPLES}, f0={F0} Hz, seed={a.seed}.\n"
        "Do not use these files to claim real-world performance.\n")
    (out / "params.json").write_text(json.dumps(
        {"fs": FS, "n_samples": N_SAMPLES, "f0": F0, "seed": a.seed}, indent=2))
    print(f"Saved {len(X)} SIMULATED waveforms to {out}/")


if __name__ == "__main__":
    main()
